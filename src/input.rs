use std::collections::{LinkedList, HashSet};
use std::fs::File;
use std::io::prelude::*;

use crate::quad_tree::WCoord;

pub struct InputState {
    pub is_paused: bool,
    pub show_grid: bool
}

impl InputState {
    pub fn new() -> Self {
        InputState {
            is_paused: true,
            show_grid: false
        }
    }
}

fn format_output_path(path: Option<&String>) -> String {
    // TODO: add more sophisticated formatting in here
    path.map_or(String::from("assets/patterns/default.rle"), |v| (*v).clone())
}

pub fn save_pattern(cells: &LinkedList<WCoord>, arg: Option<&String>, b: &Vec<usize>, s: &Vec<usize>) -> std::io::Result<()> {
    let mut init = String::new();
    init.push_str(&"#C Generated by github.com/favalosdev/game-of-life\n");
    init.push_str(&encode_run_length(cells, b, s));
    
    // Create file and write
    let path = format_output_path(arg);
    let mut file = File::create(path).unwrap();
    file.write_all(init.as_bytes()).unwrap();

    Ok(())
}

fn write_run(body: &mut String, counter: i32, alive: bool) {
    if counter > 1 {
        body.push_str(&format!("{}", counter));
    }

    body.push_str(&(if alive { "o" } else { "b" }));
}

// We know for sure that the cells container isn't empty
fn encode_run_length(cells: &LinkedList<WCoord>, b: &Vec<usize>, s: &Vec<usize>) -> String {
    if cells.is_empty() {
        return String::new();
    }
    
    let mut body = String::new();

    let mut xs = cells.iter().map(|c| c.0).collect::<Vec<isize>>();
    xs.sort_by(|a, b| a.cmp(b));

    let mut ys = cells.iter().map(|c| c.1).collect::<Vec<isize>>();
    ys.sort_by(|a, b| a.cmp(b));

    let min_x = xs[0];
    let max_x = *(xs.last().unwrap());

    let min_y = ys[0];
    let max_y = *(ys.last().unwrap());

    let span_x = max_x - min_x + 1;
    let span_y = max_y - min_y + 1;

    body.push_str(
        &format!(
            "x = {}, y = {}, rule = B{}/S{}\n",
            span_x,
            span_y,
            b.iter().map(|n| n.to_string()).collect::<String>(),
            s.iter().map(|n| n.to_string()).collect::<String>())
    );

    let lookup = cells.clone().into_iter().collect::<HashSet<WCoord>>();
    
    for y in (min_y..=max_y).rev() {
        let mut counter = 1;
        let mut last: bool = lookup.contains(&(min_x, y));

        for x in (min_x+1)..=max_x {
            let curr = lookup.contains(&(x, y));

            if curr != last {
                write_run(&mut body, counter, last);
                counter = 1;
            } else {
                counter += 1;
            }

            last = curr;
        }

        if last {
            write_run(&mut body, counter, true);
        }

        body.push_str(&(if y != min_y { "$" } else { "!" }));
    } 

    body
}
